"""sRGB and Display P3 colour profiles, generated here (no third-party profile files).

Both are ICC v2 matrix/TRC profiles with the sRGB transfer curve. The colorant matrices are derived
from the published primaries and adapted from D65 to the D50 profile connection space with the
Bradford transform, so the embedded profile and the numeric conversion in `to_display_p3` agree.
"""

from __future__ import annotations

import struct
from functools import lru_cache
from typing import cast

import numpy as np
from numpy.typing import NDArray

from pipeline.color import F32, linear_to_srgb, srgb_to_linear

Array = NDArray[np.float32]
NUL = b"\x00"

D65 = (0.3127, 0.3290)
D50_XYZ = np.array([0.9642, 1.0, 0.8249])
PRIMARIES = {
    "sRGB": ((0.640, 0.330), (0.300, 0.600), (0.150, 0.060)),
    "Display P3": ((0.680, 0.320), (0.265, 0.690), (0.150, 0.060)),
}
BRADFORD = np.array(
    [[0.8951, 0.2664, -0.1614], [-0.7502, 1.7135, 0.0367], [0.0389, -0.0685, 1.0296]]
)


def _xyz(x: float, y: float) -> NDArray[np.float64]:
    return np.array([x / y, 1.0, (1.0 - x - y) / y])


def rgb_to_xyz_d65(name: str) -> NDArray[np.float64]:
    primaries = np.column_stack([_xyz(*p) for p in PRIMARIES[name]])
    scale = np.linalg.solve(primaries, _xyz(*D65))
    return primaries * scale


def adaptation_d65_to_d50() -> NDArray[np.float64]:
    src, dst = BRADFORD @ _xyz(*D65), BRADFORD @ D50_XYZ
    return cast(NDArray[np.float64], np.linalg.inv(BRADFORD) @ np.diag(dst / src) @ BRADFORD)


def rgb_to_xyz_d50(name: str) -> NDArray[np.float64]:
    return adaptation_d65_to_d50() @ rgb_to_xyz_d65(name)


def to_display_p3(rgb: Array) -> Array:
    """Re-express sRGB-encoded pixels in Display P3 (same colours, different coordinates)."""
    matrix = np.linalg.inv(rgb_to_xyz_d65("Display P3")) @ rgb_to_xyz_d65("sRGB")
    linear = srgb_to_linear(rgb)
    out = np.tensordot(linear, matrix.astype(F32).T, axes=([-1], [0]))
    return np.clip(linear_to_srgb(np.clip(out, 0.0, 1.0).astype(F32)), 0.0, 1.0).astype(F32)


# --- ICC writer --------------------------------------------------------------------------------
def _s15(value: float) -> bytes:
    return struct.pack(">i", round(value * 65536))


def _xyz_tag(xyz: NDArray[np.float64]) -> bytes:
    return b"XYZ " + NUL * 4 + b"".join(_s15(float(v)) for v in xyz)


def _text_desc(text: str) -> bytes:
    """ICC v2 textDescriptionType: ASCII, then empty Unicode and ScriptCode parts."""
    ascii_bytes = text.encode("ascii") + NUL
    return (
        b"desc"
        + NUL * 4
        + struct.pack(">I", len(ascii_bytes))
        + ascii_bytes
        + struct.pack(">II", 0, 0)  # Unicode language code, Unicode count
        + struct.pack(">HB", 0, 0)  # ScriptCode code, count
        + NUL * 67
    )


def _text(text: str) -> bytes:
    return b"text" + NUL * 4 + text.encode("ascii") + NUL


def _srgb_curve(points: int = 1024) -> bytes:
    """ICC 'curv' maps encoded -> linear, so tabulate the sRGB decode curve."""
    xs = np.linspace(0.0, 1.0, points).astype(F32)
    table = np.round(srgb_to_linear(xs) * 65535.0).astype(">u2")
    return b"curv" + NUL * 4 + struct.pack(">I", points) + table.tobytes()


def _pad(data: bytes) -> bytes:
    return data + NUL * (-len(data) % 4)


@lru_cache(maxsize=4)
def profile_bytes(name: str) -> bytes:
    matrix = rgb_to_xyz_d50(name)
    curve = _srgb_curve()
    tags: dict[bytes, bytes] = {
        b"desc": _text_desc(name),
        b"cprt": _text("Generated by pixels. Public domain."),
        b"wtpt": _xyz_tag(D50_XYZ),
        b"rXYZ": _xyz_tag(matrix[:, 0]),
        b"gXYZ": _xyz_tag(matrix[:, 1]),
        b"bXYZ": _xyz_tag(matrix[:, 2]),
        b"rTRC": curve,
        b"gTRC": curve,
        b"bTRC": curve,
    }
    table_size = 4 + 12 * len(tags)
    offset = 128 + table_size
    table, body = b"", b""
    placed: dict[bytes, int] = {}
    for sig, data in tags.items():
        if data in placed:  # the three TRC tags share one curve
            table += sig + struct.pack(">II", placed[data], len(data))
            continue
        placed[data] = offset + len(body)
        table += sig + struct.pack(">II", offset + len(body), len(data))
        body += _pad(data)
    total = 128 + table_size + len(body)
    header = (
        struct.pack(">I", total)
        + NUL * 4  # preferred CMM
        + struct.pack(">I", 0x02400000)  # version 2.4
        + b"mntr"
        + b"RGB "
        + b"XYZ "
        + struct.pack(">6H", 2026, 1, 1, 0, 0, 0)
        + b"acsp"
        + NUL * 16  # platform, flags, manufacturer, model
        + NUL * 8  # attributes
        + struct.pack(">I", 0)  # perceptual
        + b"".join(_s15(float(v)) for v in D50_XYZ)
        + NUL * 4  # creator
        + NUL * 16  # profile id
        + NUL * 28
    )
    assert len(header) == 128
    return header + struct.pack(">I", len(tags)) + table + body
